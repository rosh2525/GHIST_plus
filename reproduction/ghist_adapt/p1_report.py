"""Summarise P0 + P1 (config_v4.json). Usage: python p1_report.py  ->  outputs_v4/summary.md, outputs_v4/figures/p1_scoreboard.png"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

OUT = Path(__file__).resolve().parent / "outputs_v4"
SLIDES = [("breast5k", "Breast5K (development)"), ("atera", "ATERA (confirmation)"), ("breast5k_pan", "Breast5K, pan-cancer model (confirmation)")]
METHODS = ["GHIST+", "GHIST+-Soft", "RRC-authors", "RRC-soft", "HAC"]
LABEL = {"GHIST+": "GHIST+ export", "GHIST+-Soft": "GHIST+-Soft (no RNA)", "RRC-authors": "authors' RRC",
         "RRC-soft": "RRC on soft score", "HAC": "HAC (ours, primary)"}
COL = {"GHIST+": "#C0392B", "GHIST+-Soft": "#E59866", "RRC-authors": "#7F8C8D", "RRC-soft": "#5B8DB8", "HAC": "#1F7A6D"}
METRICS = [("median_pcc_all", "median PCC, all genes", 1), ("median_pcc_svg20", "median PCC, top-20 SVGs", 1),
           ("median_pcc_svg50", "median PCC, top-50 SVGs", 1), ("mean_pcc_all", "mean PCC, all genes", 1),
           ("median_spearman_all", "median Spearman", 1), ("mean_rmse", "mean RMSE ↓", -1),
           ("median_rmse_pos", "RMSE, expressing cells ↓", -1), ("median_sd_ratio", "spread pred/measured (1 ideal)", 0),
           ("median_ssim_svg50", "SSIM, top-50 SVGs", 1), ("cmd_all", "CMD, all genes ↓", -1)]
CONFIG_NAMES = {"a1.0_n4_diverse": "primary: 4 × 1 mm², diverse", "a3.5_n1_diverse": "paper-matched: 1 × 3.5 mm²",
                "a1.0_n4_random": "4 × 1 mm², random"}


def better(v, ref, d):
    return abs(np.log(v)) < abs(np.log(ref)) if d == 0 else (v - ref) * d > 0


def main():
    (OUT / "figures").mkdir(parents=True, exist_ok=True)
    runs = {s: pd.read_csv(OUT / s / "runs.csv") for s, _ in SLIDES if (OUT / s / "runs.csv").exists()}
    for r in runs.values():
        r["cfg"] = r.config.str.replace(r"_s\d+$", "", regex=True)
    L = ["# P0 + P1 results (auto-generated by p1_report.py; protocol: config_v4.json)", ""]

    # zero-shot
    L += ["## Zero-shot: soft hurdle expectation vs GHIST+'s top-K gated export (no RNA used)", "",
          "| slide | cells | median PCC export → soft | top-20 SVG | top-50 SVG | mean RMSE | eval cells of all runs: soft better? |", "|---|---|---|---|---|---|---|"]
    for s, lab in SLIDES:
        if s not in runs:
            continue
        z = json.loads((OUT / s / "zero_shot.json").read_text())
        r = runs[s]
        piv = r.pivot_table(index="config", columns="method", values="median_pcc_all")
        wins = int((piv["GHIST+-Soft"] > piv["GHIST+"]).sum())
        g, so = z["GHIST+"], z["GHIST+-Soft"]
        L.append(f"| {lab} | all | {g['median_pcc_all']:.4f} → **{so['median_pcc_all']:.4f}** | {g['median_pcc_svg20']:.3f} → **{so['median_pcc_svg20']:.3f}** | "
                 f"{g['median_pcc_svg50']:.3f} → **{so['median_pcc_svg50']:.3f}** | {g['mean_rmse']:.3f} → **{so['mean_rmse']:.3f}** | {wins}/{len(piv)} runs |")
    L += [""]

    # per config scoreboards
    decision = {}
    for cfg, cname in CONFIG_NAMES.items():
        L += [f"## {cname} (mean of 3 repeats)", ""]
        hdr = "| metric | " + " | ".join(f"{lab}: " + " / ".join(m.replace("GHIST+-Soft", "Soft").replace("RRC-authors", "RRC") for m in METHODS) for s, lab in SLIDES if s in runs) + " |"
        L += [hdr, "|---|" + "---|" * len(runs)]
        for m, mlab, dirn in METRICS:
            cells = []
            for s, _ in SLIDES:
                if s not in runs:
                    continue
                t = runs[s][runs[s].cfg == cfg].groupby("method")[m].mean()
                vals = [t.get(x, np.nan) for x in METHODS]
                best = METHODS[int(np.nanargmax([v * dirn if dirn else -abs(np.log(v)) for v in vals]))]
                cells.append(" / ".join(f"**{v:.3f}**" if x == best else f"{v:.3f}" for x, v in zip(METHODS, vals)))
            L.append(f"| {mlab} | " + " | ".join(cells) + " |")
        L += [""]
        for s, _ in SLIDES:
            if s not in runs:
                continue
            h = runs[s][(runs[s].cfg == cfg) & (runs[s].method == "HAC")]
            rr = runs[s][(runs[s].cfg == cfg) & (runs[s].method == "RRC-authors")]
            n_ci = int((h["ci_vs_RRC-authors_all_lo"] > 0).sum())
            guard = {k: float(h[k].mean() / rr[k].mean() - 1) for k in ("mean_rmse", "median_rmse_pos")}
            guard["ssim"] = float(rr["median_ssim_svg50"].mean() / h["median_ssim_svg50"].mean() - 1)
            decision[(s, cfg)] = (h.median_pcc_all.mean() > rr.median_pcc_all.mean(), n_ci, guard)
        L += ["HAC vs authors' RRC on median PCC (all genes): " + "; ".join(
            f"{s}: mean {runs[s][(runs[s].cfg == cfg) & (runs[s].method == 'HAC')].median_pcc_all.mean():.4f} vs "
            f"{runs[s][(runs[s].cfg == cfg) & (runs[s].method == 'RRC-authors')].median_pcc_all.mean():.4f}, CI>0 in {decision[(s, cfg)][1]}/3 repeats"
            for s, _ in SLIDES if s in runs), ""]

    # decision rule (headline = primary config)
    L += ["## Pre-declared decision (config_v4.json, primary config)", ""]
    ok_all = True
    for s, lab in SLIDES:
        if (s, "a1.0_n4_diverse") not in decision:
            continue
        win, nci, g = decision[(s, "a1.0_n4_diverse")]
        guard_ok = all(v <= 0.02 for v in g.values())
        ok = win and nci >= 2 and guard_ok
        ok_all &= ok
        L.append(f"- {lab}: mean better = {win}; CI excludes 0 in {nci}/3; guardrails vs RRC (positive = HAC worse): "
                 f"RMSE {100*g['mean_rmse']:+.1f}%, RMSE expressing {100*g['median_rmse_pos']:+.1f}%, SSIM {100*g['ssim']:+.1f}% → **{'PASS' if ok else 'FAIL'}**")
    L += ["", f"**Overall: HAC {'improves on' if ok_all else 'does not meet the bar against'} the authors' RRC under the pre-declared rule.**", ""]

    # P0 diagnostic
    L += ["## P0 diagnostic: optimism of the authors' RRC hyperparameter selection", "",
          "Mean per-gene PCC of authors' RRC: its own selection score (random 20% of core cells), leave-one-core-out score, and the real score on the withheld slide.", "",
          "| slide | config | random-20% score | leave-one-core-out | withheld slide |", "|---|---|---|---|---|"]
    for s, _ in SLIDES:
        if s not in runs:
            continue
        r = runs[s][runs[s].method == "RRC-authors"].groupby("cfg")[["rrc_cv_random20", "rrc_cv_loco", "mean_pcc_all"]].mean()
        for cfg, row in r.iterrows():
            L.append(f"| {s} | {CONFIG_NAMES.get(cfg, cfg)} | {row.rrc_cv_random20:.4f} | {row.rrc_cv_loco:.4f} | {row.mean_pcc_all:.4f} |")
    L += [""]
    (OUT / "summary.md").write_text("\n".join(L) + "\n")

    # figure: median PCC by method, per slide x config
    fig, axes = plt.subplots(1, len(runs), figsize=(6.5 * len(runs), 4.4), squeeze=False)
    for j, (s, lab) in enumerate([x for x in SLIDES if x[0] in runs]):
        ax = axes[0, j]
        r = runs[s]
        cfgs = list(CONFIG_NAMES)
        w = 0.16
        for k, m in enumerate(METHODS):
            g = r[r.method == m].groupby("cfg").median_pcc_all
            mu, sd = g.mean().reindex(cfgs), g.std().reindex(cfgs)
            ax.bar(np.arange(len(cfgs)) + (k - 2) * w, mu, w, yerr=sd, capsize=2, color=COL[m], label=LABEL[m])
        ax.set_xticks(range(len(cfgs)), [CONFIG_NAMES[c].split(":")[0] for c in cfgs])
        ax.set_ylabel("median per-gene PCC (withheld slide)"); ax.set_title(lab, fontsize=10)
        lo = r.median_pcc_all.min() * 0.85; ax.set_ylim(lo, r.median_pcc_all.max() * 1.22)
    axes[0, 0].legend(fontsize=8, loc="upper left")
    fig.suptitle("P1: hurdle-aware correction vs the authors' RRC (mean ± SD of 3 repeats)", fontsize=10)
    fig.tight_layout(); fig.savefig(OUT / "figures" / "p1_scoreboard.png", dpi=150); plt.close(fig)
    print("\n".join(L))


if __name__ == "__main__":
    main()
