"""Aggregate v3 runs into tables and figures.

Usage:  python report_v3.py
Writes  outputs/summary.md, outputs/headline_scoreboard.csv, outputs/figures/*.png, outputs/<slide>/programme_weights.csv
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from run_v3 import MARKERS

HERE = Path(__file__).resolve().parent
OUT = Path(os.getenv("V3_OUT") or HERE / "outputs")
FIG = OUT / "figures"
SLIDES = [("breast5k", "Breast5K (development)"), ("atera", "ATERA (confirmation)"), ("breast2", "BreastCancer2 (confirmation)")]
COL = {"GHIST+": "#C0392B", "calibration": "#E1A33B", "ridge": "#5B8DB8", "Adapt": "#1F7A6D", "Adapt-DM": "#7B5EA7"}
LABEL = {"GHIST+": "GHIST+ (frozen)", "calibration": "Per-gene calibration", "ridge": "Ridge only",
         "Adapt": "GHIST+-Adapt", "Adapt-DM": "GHIST+-Adapt-DM"}
# metric, label, direction (+1 higher better, -1 lower better, 0 closer to 1 better)
METRICS = [("median_pcc_all", "median PCC, all genes", 1), ("median_pcc_svg20", "median PCC, top-20 SVGs", 1),
           ("median_pcc_svg50", "median PCC, top-50 SVGs", 1), ("median_spearman_all", "median Spearman, all genes", 1),
           ("mean_rmse", "mean RMSE (log1p)", -1), ("median_rmse_pos", "median RMSE, measured>0", -1),
           ("median_sd_ratio", "SD ratio pred/measured (1 = ideal)", 0), ("median_ssim_svg50", "median SSIM, top-50 SVGs", 1),
           ("median_ssim_nonsvg50", "median SSIM, top-50 non-SVGs", 1), ("cmd_all", "CMD, all genes", -1),
           ("cmd_svg50", "CMD, top-50 SVGs", -1), ("median_programme_pcc", "cell-type programme PCC (median)", 1)]
HEAD = {"primary": (1.0, 4, "diverse"), "paper_matched": (3.5, 1, "diverse")}


def better(v, ref, direction):
    if direction == 0:
        return abs(np.log(v)) < abs(np.log(ref))
    return (v - ref) * direction > 0


def headline(runs, cfg):
    a, n, pl = cfg
    return runs[(runs.core_area_mm2 == a) & (runs.n_cores == n) & (runs.placement == pl)]


def main():
    FIG.mkdir(parents=True, exist_ok=True)
    runs = {s: pd.read_csv(OUT / s / "runs.csv") for s, _ in SLIDES if (OUT / s / "runs.csv").exists()}
    lines = ["# GHIST+-Adapt v3 results (auto-generated by report_v3.py)", "",
             "Mean over 3 repeats of the core placement. Evaluation = every cell >200 um from all cores. "
             "✅ = better than GHIST+ on that metric (for median PCC also requires the block-bootstrap 95% CI of the gain to exclude 0 in every repeat).", ""]
    board = []
    for hname, cfg in HEAD.items():
        lines += [f"## {hname.replace('_', ' ')} config: {cfg[1]} core(s) x {cfg[0]} mm², {cfg[2]} placement", ""]
        hdr = "| metric | " + " | ".join(f"{lab}: GHIST+ → Adapt (Adapt-DM)" for s, lab in SLIDES if s in runs) + " |"
        lines += [hdr, "|---|" + "---|" * len(runs)]
        per_slide = {}
        for s, _ in SLIDES:
            if s not in runs:
                continue
            h = headline(runs[s], cfg)
            if h.empty:
                continue
            per_slide[s] = h.groupby("method").mean(numeric_only=True)
            ad = h[h.method == "Adapt"]
            per_slide[s].loc["Adapt", "ci_all_excl0"] = bool((ad.boot_diff_all_lo > 0).all()) if len(ad) else False
            per_slide[s].loc["Adapt", "ci_svg20_excl0"] = bool((ad.boot_diff_svg20_lo > 0).all()) if len(ad) else False
        for m, lab, dirn in METRICS:
            cells = []
            for s, _ in SLIDES:
                if s not in per_slide:
                    continue
                t = per_slide[s]
                g, a, dm = t.loc["GHIST+", m], t.loc["Adapt", m], t.loc["Adapt-DM", m]
                ok = better(a, g, dirn)
                if m == "median_pcc_all":
                    ok = ok and bool(t.loc["Adapt", "ci_all_excl0"])
                if m == "median_pcc_svg20":
                    ok = ok and bool(t.loc["Adapt", "ci_svg20_excl0"])
                cells.append(f"{g:.3f} → **{a:.3f}** ({dm:.3f}) {'✅' if ok else '❌'}")
                board.append({"config": hname, "slide": s, "metric": m, "GHIST+": g, "Adapt": a, "Adapt-DM": dm, "Adapt_better": ok,
                              "Adapt-DM_better": better(dm, g, dirn)})
            lines.append(f"| {lab} | " + " | ".join(cells) + " |")
        cov = []
        for s, _ in SLIDES:
            if s in per_slide:
                t = per_slide[s].loc["Adapt"]
                cov.append(f"{s}: Adapt {t.conformal_coverage_median:.3f} cov / width {t.conformal_width_mean:.3f} vs "
                           f"GHIST+ {t.ghist_conformal_coverage_median:.3f} / {t.ghist_conformal_width_mean:.3f}")
        lines += ["", "90% conformal intervals (median coverage over genes / mean width): " + "; ".join(cov), ""]
        n_cells = {s: int(headline(runs[s], cfg).groupby("seed").n_anchor_cells.first().mean()) for s in per_slide}
        lines += ["Anchor cells (mean): " + ", ".join(f"{s} {v:,}" for s, v in n_cells.items()), ""]
    pd.DataFrame(board).to_csv(OUT / "headline_scoreboard.csv", index=False, float_format="%.5f")

    # learning curves: median PCC vs total core area
    fig, axes = plt.subplots(2, len(runs), figsize=(5.2 * len(runs), 8), squeeze=False)
    for j, (s, lab) in enumerate([x for x in SLIDES if x[0] in runs]):
        r = runs[s]
        for i, (m, ylab) in enumerate([("median_pcc_all", "median PCC, all genes"), ("median_pcc_svg20", "median PCC, top-20 SVGs")]):
            ax = axes[i, j]
            for meth in ["GHIST+", "calibration", "Adapt", "Adapt-DM"]:
                for pl, ls in (("diverse", "-"), ("random", ":")):
                    g = r[(r.method == meth) & (r.placement == pl)].groupby("total_core_area_mm2")[m]
                    mu = g.mean()
                    ax.plot(mu.index, mu.values, ls, marker="o", ms=3, color=COL[meth],
                            label=f"{LABEL[meth]} ({pl})" if (i == 0 and j == 0) else None)
            ax.set_xscale("log"); ax.set_xlabel("total core area (mm², log)"); ax.set_ylabel(ylab)
            if i == 0:
                ax.set_title(lab, fontsize=10)
    axes[0, 0].legend(fontsize=7, ncol=1)
    fig.suptitle("Gain vs measured-core budget (solid = RNA-free diverse placement, dotted = random); mean of 3 repeats", fontsize=10)
    fig.tight_layout(); fig.savefig(FIG / "learning_curves.png", dpi=150); plt.close(fig)

    # headline scoreboard figure: relative change vs GHIST+
    b = pd.DataFrame(board)
    b = b[b.config == "primary"]
    fig, axes = plt.subplots(1, len(runs), figsize=(5.0 * len(runs), 5.2), sharey=True, squeeze=False)
    for j, (s, lab) in enumerate([x for x in SLIDES if x[0] in runs]):
        t = b[b.slide == s].set_index("metric")
        ax = axes[0, j]
        if t.empty:
            continue
        ys = np.arange(len(METRICS))
        for k, (meth, off) in enumerate((("Adapt", -0.18), ("Adapt-DM", 0.18))):
            vals = []
            for m, _, dirn in METRICS:
                g, v = t.loc[m, "GHIST+"], t.loc[m, meth]
                if dirn == 0:
                    vals.append(100 * (abs(np.log(g)) - abs(np.log(v))) / abs(np.log(g)))
                else:
                    vals.append(100 * dirn * (v - g) / abs(g))
            ax.barh(ys + off, np.clip(vals, -100, 300), height=0.34, color=COL[meth], label=LABEL[meth])
        ax.axvline(0, color="k", lw=0.8)
        ax.set_yticks(ys, [lab_ for _, lab_, _ in METRICS], fontsize=8); ax.invert_yaxis()
        ax.set_xlabel("% improvement over GHIST+ (positive = better)"); ax.set_title(lab, fontsize=10)
    axes[0, 0].legend(fontsize=8, loc="lower right")
    fig.suptitle("Primary config: 4 cores x 1 mm², RNA-free diverse placement (mean of 3 repeats)", fontsize=10)
    fig.tight_layout(); fig.savefig(FIG / "scoreboard_primary.png", dpi=150); plt.close(fig)

    # biology 1: cell-type programme recovery
    progs = list(MARKERS)
    fig, axes = plt.subplots(1, len(runs), figsize=(5.0 * len(runs), 4.2), sharey=True, squeeze=False)
    for j, (s, lab) in enumerate([x for x in SLIDES if x[0] in runs]):
        h = headline(runs[s], HEAD["primary"]).groupby("method").mean(numeric_only=True)
        have = [p for p in progs if f"programme_pcc_{p}" in h.columns and np.isfinite(h.loc["GHIST+", f"programme_pcc_{p}"])]
        x = np.arange(len(have))
        for meth, off in (("GHIST+", -0.2), ("Adapt", 0.2)):
            axes[0, j].bar(x + off, [h.loc[meth, f"programme_pcc_{p}"] for p in have], width=0.38, color=COL[meth], label=LABEL[meth])
        axes[0, j].set_xticks(x, have, rotation=45, ha="right"); axes[0, j].set_title(lab, fontsize=10)
    axes[0, 0].set_ylabel("PCC of programme score (pred vs measured)"); axes[0, 0].legend(fontsize=8)
    fig.suptitle("Cell-type marker programme recovery (authors' marker sets), primary config", fontsize=10)
    fig.tight_layout(); fig.savefig(FIG / "programme_recovery.png", dpi=150); plt.close(fig)

    # biology 2: what the adapter learned (headline seed-0 weights)
    lines += ["## What the adapter learned (biology)", "",
              "For each corrected gene that belongs to a marker programme: the share of its correction weight (|W|, standardised inputs, self excluded) "
              "that comes from other genes of the *same* programme, divided by the share expected if weight were spread evenly. >1 = the correction uses biologically related genes. "
              "Signs in the examples: + = higher input raises the corrected gene, − = lowers it (e.g. mutually exclusive compartments). "
              "Co-expressed inputs are correlated, so weights reflect co-expression structure, not causal regulation.", "",
              "| slide | programme | genes (corrected) | mean within-programme enrichment | example: top inputs |", "|---|---|---|---|---|"]
    for s, _ in SLIDES:
        p = OUT / s / "headline_weights.npz"
        if not p.exists():
            continue
        z = np.load(p)
        Ws, use, genes = z["W"], z["use_ridge"], z["genes"].astype(str).tolist()
        W = np.abs(Ws)
        sgn = lambda i, g: "+" if Ws[i, g] >= 0 else "−"
        G = len(genes)
        rows = []
        for prog, mk in MARKERS.items():
            idx = [genes.index(g) for g in mk if g in genes]
            if len(idx) < 2:
                continue
            enr = []
            example = ""
            for g in idx:
                if not use[g]:
                    continue
                w = W[:, g].copy(); w[g] = 0
                if w.sum() == 0:
                    continue
                share = w[[i for i in idx if i != g]].sum() / w.sum()
                expect = (len(idx) - 1) / (G - 1)
                enr.append(share / expect)
                if not example:
                    top = np.argsort(-w)[:4]
                    example = f"{genes[g]} ← " + ", ".join(f"{sgn(t, g)}{genes[t]}" for t in top)
                rows.append({"programme": prog, "gene": genes[g], "within_share": share, "expected": expect, "enrichment": share / expect,
                             "top_inputs": ";".join(f"{sgn(t, g)}{genes[t]}" for t in np.argsort(-w)[:5])})
            if enr:
                lines.append(f"| {s} | {prog} | {len(idx)} ({len(enr)}) | {np.mean(enr):.1f}× | {example} |")
        pd.DataFrame(rows).to_csv(OUT / s / "programme_weights.csv", index=False, float_format="%.4f")
        # programme-to-programme weight map
        names = [k for k, v in MARKERS.items() if sum(g in genes for g in v) >= 2]
        M = np.zeros((len(names), len(names)))
        for a_, pa in enumerate(names):
            ia = [genes.index(g) for g in MARKERS[pa] if g in genes]
            for b_, pb in enumerate(names):
                ib = [genes.index(g) for g in MARKERS[pb] if g in genes]
                sub = W[np.ix_(ib, ia)].copy()
                if pa == pb:
                    np.fill_diagonal(sub, 0)
                M[a_, b_] = sub.sum() / max(1, len(ia) * len(ib) - (len(ia) if pa == pb else 0))
        M = M / (W.sum() / (G * G))
        fig, ax = plt.subplots(figsize=(5.4, 4.6))
        im = ax.imshow(M, cmap="viridis")
        ax.set_xticks(range(len(names)), names, rotation=45, ha="right"); ax.set_yticks(range(len(names)), names)
        ax.set_xlabel("input programme"); ax.set_ylabel("corrected programme")
        plt.colorbar(im, label="mean |weight| / slide average")
        ax.set_title(f"{s}: which programmes inform which corrections", fontsize=9)
        fig.tight_layout(); fig.savefig(FIG / f"programme_weight_map_{s}.png", dpi=150); plt.close(fig)
    lines += ["", "## Every config", "", "Per-config means are in each slide's runs.csv; skipped configs (core area > 20% of tissue) are listed in cores.json.", ""]
    for s, _ in SLIDES:
        if s not in runs:
            continue
        r = runs[s]
        t = (r[r.method.isin(["GHIST+", "Adapt"])]
             .groupby(["n_cores", "core_area_mm2", "placement", "method"]).median_pcc_all.mean().unstack("method"))
        t["gain"] = t["Adapt"] - t["GHIST+"]
        lines += [f"### {s}: median PCC (all genes) by config", "", t.round(4).to_markdown(), ""]
    (OUT / "summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:60]))


if __name__ == "__main__":
    main()
